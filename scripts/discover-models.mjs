import { readdir, readFile, mkdir, writeFile, access } from "node:fs/promises";
import { join } from "node:path";
const root = join(process.cwd(), "src/models");
const folders = (await readdir(root, { withFileTypes: true }))
  .filter((x) => x.isDirectory())
  .map((x) => x.name)
  .sort();
const models = [];
for (const slug of folders) {
  const data = JSON.parse(
    await readFile(join(root, slug, "metadata.json"), "utf8"),
  );
  if (
    data.slug !== slug ||
    !data.title ||
    !["live", "coming-soon"].includes(data.status)
  )
    throw new Error(`Invalid model metadata: ${slug}`);
  if (data.status === "live") await access(join(root, slug, "index.tsx"));
  models.push(data);
}
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/models.ts",
  `// Generated by scripts/discover-models.mjs. Do not edit.\nimport type { ModelMetadata } from '@/lib/model';\nexport const models: ModelMetadata[] = ${JSON.stringify(models, null, 2)};\nexport const modelLoaders = {\n${models
    .filter((m) => m.status === "live")
    .map((m) => ` '${m.slug}': () => import('../models/${m.slug}/index'),`)
    .join("\n")}\n};\n`,
);
console.log(
  `Discovered ${models.length} models (${models.filter((m) => m.status === "live").length} live).`,
);
